package com.sakshi.operator;

public class Operator1 {
	public static void main(String[] args) {
		System.out.println("Hello Sakshi");
		int a = 10,b=20;
		System.out.println("a>b : "+(a>b));
		System.out.println("a<b : "+(a<b));
		System.out.println("a==b : "+(a==b));
		System.out.println("a>=b : "+(a>=b));
		System.out.println("a<=b : "+(a<=b));
		System.out.println("a!=b : "+(a!=b));
	}
}
